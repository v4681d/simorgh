//! Pipeline orchestration. Each stage runs as an independent tokio task,
//! connected by bounded channels (backpressure). Pipelines restart cleanly on
//! device/engine change without restarting the app: `PipelineHandle::stop`
//! aborts every stage task and drops the channels.

use crate::latency::LatencyRecorder;
use crate::policy::PolicySettings;
use crate::traits::*;
use crate::types::*;
use crate::{Error, Result};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::time::{Duration, Instant};
use tokio::sync::{mpsc, watch};
use tracing::{info, warn};

/// Bounded channel depth between stages — small enough for backpressure,
/// large enough to ride out engine hiccups.
const CHANNEL_DEPTH: usize = 32;

/// Feedback-loop gate: Pipeline A must never transcribe audio generated by
/// Pipeline B. While TTS is speaking (and for a short tail), the gate is
/// closed and Pipeline A drops loopback frames. Frames explicitly flagged
/// `self_generated` are always dropped.
#[derive(Clone, Default)]
pub struct SelfAudioGate {
    speaking: Arc<AtomicBool>,
}

impl SelfAudioGate {
    pub fn set_speaking(&self, speaking: bool) {
        self.speaking.store(speaking, Ordering::SeqCst);
    }
    pub fn should_drop(&self, frame: &AudioFrame) -> bool {
        frame.self_generated || self.speaking.load(Ordering::SeqCst)
    }
}

/// Everything a pipeline needs, resolved from config by the app layer.
pub struct PipelineDeps {
    pub stt: Arc<dyn SttEngine>,
    pub translator: Arc<dyn Translator>,
    /// TTS is only used by the Voice pipeline.
    pub tts: Option<Arc<dyn TtsEngine>>,
    pub policy: Box<dyn CommitPolicy>,
    pub pair: LangPair,
    pub latency: Arc<LatencyRecorder>,
    pub gate: SelfAudioGate,
    pub settings: PolicySettings,
}

/// Events emitted to the UI layer (Tauri forwards them to windows).
#[derive(Debug, Clone, serde::Serialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum PipelineEvent {
    State { kind: PipelineKind, state: PipelineState },
    Transcript(TranscriptSegment),
    Translation(TranslationUpdate),
    Level { kind: PipelineKind, rms: f32, peak: f32 },
}

pub struct PipelineHandle {
    pub kind: PipelineKind,
    state_tx: watch::Sender<PipelineState>,
    tasks: Vec<tokio::task::JoinHandle<()>>,
}

impl PipelineHandle {
    pub fn state(&self) -> PipelineState {
        *self.state_tx.borrow()
    }
    pub fn stop(&mut self) {
        for t in self.tasks.drain(..) {
            t.abort();
        }
        let _ = self.state_tx.send(PipelineState::Stopped);
        info!(kind = ?self.kind, "pipeline stopped");
    }
}

impl Drop for PipelineHandle {
    fn drop(&mut self) {
        self.stop();
    }
}

/// Pipeline A — Listen & subtitle:
/// loopback audio -> gate -> STT (streaming) -> retranslation policy -> MT -> overlay events.
pub async fn start_subtitle_pipeline(
    mut deps: PipelineDeps,
    audio_rx: mpsc::Receiver<AudioFrame>,
    events_tx: mpsc::Sender<PipelineEvent>,
) -> Result<PipelineHandle> {
    let (state_tx, _) = watch::channel(PipelineState::Starting);
    let (gated_tx, gated_rx) = mpsc::channel::<AudioFrame>(CHANNEL_DEPTH);
    let (seg_tx, mut seg_rx) = mpsc::channel::<TranscriptSegment>(CHANNEL_DEPTH);

    // Stage 1: gate (drop self-generated audio to prevent feedback loops).
    let gate = deps.gate.clone();
    let gate_task = tokio::spawn(gate_stage(audio_rx, gated_tx, gate));

    // Stage 2: streaming STT session (owned task inside the engine).
    let stt_session = deps
        .stt
        .start_session(deps.pair.source.clone(), gated_rx, seg_tx)
        .await?;

    // Stage 3: policy + translation. Superseded in-flight translations are
    // aborted — only the newest partial is worth translating.
    let translator = deps.translator.clone();
    let pair = deps.pair.clone();
    let latency = deps.latency.clone();
    let events = events_tx.clone();
    let translate_task = tokio::spawn(async move {
        let mut inflight: Option<tokio::task::JoinHandle<()>> = None;
        let mut tick = tokio::time::interval(Duration::from_millis(250));
        let started = Instant::now();
        let mut current: Option<TranscriptSegment> = None;
        loop {
            let decision = tokio::select! {
                seg = seg_rx.recv() => {
                    let Some(seg) = seg else { break };
                    let now_ms = started.elapsed().as_millis() as u64;
                    let _ = events.send(PipelineEvent::Transcript(seg.clone())).await;
                    let d = deps.policy.on_transcript(&seg, now_ms);
                    current = Some(seg);
                    d
                }
                _ = tick.tick() => {
                    deps.policy.on_tick(started.elapsed().as_millis() as u64)
                }
            };
            let (text, is_final) = match decision {
                CommitDecision::Hold => continue,
                CommitDecision::Provisional(t) => (t, false),
                CommitDecision::Commit(t) => (t, true),
            };
            let Some(seg) = current.clone() else { continue };
            // Cancel a superseded in-flight translation (provisional only).
            if let Some(h) = inflight.take() {
                if !is_final { h.abort(); } else { let _ = h.await; }
            }
            let translator = translator.clone();
            let pair = pair.clone();
            let events = events.clone();
            let latency = latency.clone();
            inflight = Some(tokio::spawn(async move {
                let t0 = Instant::now();
                match translator.translate(&text, &pair).await {
                    Ok(translated) => {
                        latency.record(Stage::Translate, t0.elapsed());
                        let _ = events
                            .send(PipelineEvent::Translation(TranslationUpdate {
                                segment_id: seg.id,
                                source_text: text,
                                translated_text: translated,
                                lang: pair,
                                is_final,
                            }))
                            .await;
                    }
                    Err(e) => warn!(error = %e, "translation failed"),
                }
            }));
        }
    });

    let _ = state_tx.send(PipelineState::Running);
    let _ = events_tx
        .send(PipelineEvent::State { kind: PipelineKind::Subtitle, state: PipelineState::Running })
        .await;
    Ok(PipelineHandle {
        kind: PipelineKind::Subtitle,
        state_tx,
        tasks: vec![gate_task, stt_session.handle_task(), translate_task],
    })
}

/// Pipeline B — Speak & translate:
/// mic -> VAD -> STT -> clause-commit policy -> MT -> TTS -> virtual mic sink.
/// TTS output raises the SelfAudioGate so Pipeline A ignores it.
pub async fn start_voice_pipeline(
    mut deps: PipelineDeps,
    audio_rx: mpsc::Receiver<AudioFrame>,
    sink_tx: mpsc::Sender<AudioFrame>,
    events_tx: mpsc::Sender<PipelineEvent>,
) -> Result<PipelineHandle> {
    let tts = deps.tts.clone().ok_or_else(|| Error::Config("voice pipeline requires a TTS engine".into()))?;
    let (state_tx, _) = watch::channel(PipelineState::Starting);
    let (seg_tx, mut seg_rx) = mpsc::channel::<TranscriptSegment>(CHANNEL_DEPTH);

    let stt_session = deps
        .stt
        .start_session(deps.pair.source.clone(), audio_rx, seg_tx)
        .await?;

    let translator = deps.translator.clone();
    let pair = deps.pair.clone();
    let latency = deps.latency.clone();
    let gate = deps.gate.clone();
    let events = events_tx.clone();
    let target = pair.target.clone();
    let voice_task = tokio::spawn(async move {
        let started = Instant::now();
        let mut tick = tokio::time::interval(Duration::from_millis(250));
        loop {
            let decision = tokio::select! {
                seg = seg_rx.recv() => {
                    let Some(seg) = seg else { break };
                    let now_ms = started.elapsed().as_millis() as u64;
                    let _ = events.send(PipelineEvent::Transcript(seg.clone())).await;
                    if seg.is_final {
                        deps.policy.on_speech_end(&seg)
                    } else {
                        deps.policy.on_transcript(&seg, now_ms)
                    }
                }
                _ = tick.tick() => deps.policy.on_tick(started.elapsed().as_millis() as u64),
            };
            // Voice is irreversible: only Commit decisions reach TTS.
            let CommitDecision::Commit(text) = decision else { continue };
            let t0 = Instant::now();
            let translated = match translator.translate(&text, &pair).await {
                Ok(t) => { latency.record(Stage::Translate, t0.elapsed()); t }
                Err(e) => { warn!(error = %e, "translation failed"); continue }
            };
            let _ = events
                .send(PipelineEvent::Translation(TranslationUpdate {
                    segment_id: uuid::Uuid::new_v4(),
                    source_text: text,
                    translated_text: translated.clone(),
                    lang: pair.clone(),
                    is_final: true,
                }))
                .await;
            // Synthesize into the virtual mic; close the gate while speaking.
            gate.set_speaking(true);
            let t1 = Instant::now();
            if let Err(e) = tts.synthesize(&translated, target.clone(), sink_tx.clone()).await {
                warn!(error = %e, "tts failed");
            }
            latency.record(Stage::Tts, t1.elapsed());
            gate.set_speaking(false);
        }
    });

    let _ = state_tx.send(PipelineState::Running);
    let _ = events_tx
        .send(PipelineEvent::State { kind: PipelineKind::Voice, state: PipelineState::Running })
        .await;
    Ok(PipelineHandle {
        kind: PipelineKind::Voice,
        state_tx,
        tasks: vec![stt_session.handle_task(), voice_task],
    })
}

async fn gate_stage(
    mut rx: mpsc::Receiver<AudioFrame>,
    tx: mpsc::Sender<AudioFrame>,
    gate: SelfAudioGate,
) {
    while let Some(frame) = rx.recv().await {
        if gate.should_drop(&frame) {
            continue;
        }
        if tx.send(frame).await.is_err() {
            break;
        }
    }
}

impl SttSession {
    /// Detach the join handle so the pipeline owns task lifetime.
    fn handle_task(mut self) -> tokio::task::JoinHandle<()> {
        let h = std::mem::replace(&mut self.handle, tokio::spawn(async { Ok(()) }));
        std::mem::forget(self); // don't abort the real task in Drop
        tokio::spawn(async move {
            if let Err(e) = h.await.unwrap_or(Ok(())) {
                warn!(error = %e, "stt session ended with error");
            }
        })
    }
}
